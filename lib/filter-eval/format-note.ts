import { APPLY_KEYS, REQUIRED_KEYS } from "./filter-ast.ts";
import type { ApplyKey } from "./filter-ast.ts";

/**
 * Write the `#@` line a block ends with.
 *
 * The inverse of what `parse-filter.ts` reads, and it lives here so the two cannot drift:
 * a generator that builds the line by hand can spell it wrong and only find out when the
 * filter fails to load. Everything this writes, `parseFilter` reads back unchanged.
 *
 * Keys come out in the order `APPLY_KEYS` declares them, so the same notes always produce
 * the same line and two generated filters can be compared as text.
 */
export function formatNote(
  notes: Readonly<Partial<Record<ApplyKey, string>>>,
  freehand = "",
): string {
  for (const required of REQUIRED_KEYS) {
    if (notes[required] === undefined) {
      fail(`a note needs ${REQUIRED_KEYS.join(" and ")}, and this one has no ${required}`);
    }
  }

  const pairs: string[] = [];

  for (const key of Object.keys(APPLY_KEYS) as ApplyKey[]) {
    const value = notes[key];
    if (value === undefined) continue;

    const allowed = APPLY_KEYS[key] as readonly string[];
    if (!allowed.includes(value)) {
      fail(`${key} takes one of ${allowed.join(", ")}, got ${JSON.stringify(value)}`);
    }

    pairs.push(`${key}=${value}`);
  }

  const tail = freehand.trim();
  if (tail === "") return `#@ ${pairs.join(" ")}`;

  if (/[\r\n]/.test(tail)) {
    fail("freehand cannot span lines, because the note is one line");
  }
  // The reader starts the freehand at the first token with no `=`. A first token that has
  // one would be read as a botched pair and throw, so it is refused here instead.
  const first = tail.split(/\s+/)[0] ?? "";
  if (first.includes("=")) {
    fail(`freehand cannot start with ${JSON.stringify(first)}, because it looks like a pair`);
  }

  return `#@ ${pairs.join(" ")} ${tail}`;
}

const fail = (message: string): never => {
  throw new Error(`cannot write a #@ note: ${message}`);
};

/**
 * Write a condition line, with an optional comment saying where it came from.
 *
 * ```
 * AreaLevel >= 68 # generated by bucket unique:Heavy Belt
 * ```
 *
 * A condition the generation phase adds is a real condition line, never a marker of its
 * own. A marker would be a comment, the game would skip it, and the filter being validated
 * would not be the filter that runs. Provenance rides in the trailing comment instead,
 * which `parseFilter` keeps on the condition for a person to read back.
 */
export function formatCondition(condition: string, comment = ""): string {
  const written = condition.trim();

  if (written === "") wrong("it is empty");
  if (/[\r\n]/.test(written)) wrong("a condition is one line");
  if (written.startsWith("#")) {
    wrong(`${JSON.stringify(condition)} is already a comment`);
  }
  // A `#` would end the condition and start the comment, so the caller cannot smuggle one
  // in and expect the whole line to survive.
  if (written.includes("#")) {
    wrong(`${JSON.stringify(condition)} has a # in it, which would start the comment`);
  }

  const note = comment.trim();
  if (/[\r\n]/.test(note)) wrong("the comment is more than one line");

  return note === "" ? written : `${written} # ${note}`;
}

const wrong = (message: string): never => {
  throw new Error(`cannot write a condition line: ${message}`);
};
